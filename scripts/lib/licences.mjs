/** NC, ND, SA as a token in any separator (CC BY-NC 4.0, CC_BY_NC_4.0), their spelled-out names, BBC RemArc. */
export const FORBIDDEN_ID = /(^|[^a-z])(nc|nd|sa)([^a-z]|$)|non-?commercial|no-?deriv|share-?alike|remarc/i;
/** A Creative Commons NC, ND or SA licence page, e.g. https://creativecommons.org/licenses/by-nc/4.0/. */
export const FORBIDDEN_URL = /creativecommons\.org\/licenses\/by-(nc|nd|sa)/i;
/** Own work's sourceUrl lives in this public repository (ADR 0016). */
export const OWN_REPO_PATH = "/kudratsingh/jungle-world";

/** Never allowed, not even as an exception: NC (a job-seeking portfolio is arguably commercial), ND
 * (decimating and recompressing is a modification), SA, and BBC RemArc; by id, or by licence URL. */
export function isForbidden(id, url) {
  return (typeof id === "string" && FORBIDDEN_ID.test(id)) || (typeof url === "string" && FORBIDDEN_URL.test(url));
}

/** True when `v` is an https://github.com URL inside the public jungle-world repository, with no dot-segments. */
export function isOwnSourceUrl(v) {
  if (typeof v !== "string" || /%2e/i.test(v) || /\/\.\.?(\/|$|[?#])/.test(v)) return false;
  let u;
  try {
    u = new URL(v);
  } catch {
    return false;
  }
  return u.origin === "https://github.com" && (u.pathname === OWN_REPO_PATH || u.pathname.startsWith(`${OWN_REPO_PATH}/`));
}

