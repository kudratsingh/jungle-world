/** Own work's title ends with a tool name and a dotted version, e.g. "EZ-Tree 1.1.0" (ADR 0016). */
export const OWN_TITLE = /\S\s+v?\d+(\.\d+)+\S*$/;

export function licenceInfo(id) {
  return Object.hasOwn(LICENCES, id) ? LICENCES[id] : null;
}
